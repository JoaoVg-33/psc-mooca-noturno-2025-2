public class calculadora{

    public void soma(int a, int b){
        int resultado;
        resultado = a + b;
        return resultado;
    }

    public void subtracao(int a, int b){
        int resultado;
        resultado = a - b;
        return resultado;
    }

    public void multiplicacao(int a, int b){
        int resultado;
        resultado = a * b;
        return resultado;
    }

    public void divisao(int a, int b){
        int resultado;
        resultado = a / b;
        return resultado;
    }
}

